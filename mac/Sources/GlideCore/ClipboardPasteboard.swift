import AppKit
import Foundation

/// NSPasteboard side of clipboard sync (PROTOCOL.md §5). Takes the pasteboard as a parameter so
/// the selftest can use a private named pasteboard instead of the user's general one.

/// Why local content is not sent (logged by the caller).
public struct ClipboardRefusal: Error, Equatable {
    public let reason: String
    public init(_ reason: String) { self.reason = reason }
}

/// What the local pasteboard holds, as read for sending.
public enum PasteboardContent: Equatable {
    /// Text in wire form (LF line endings).
    case text(String)
    /// An existing `public.png` representation (sent byte-for-byte).
    case png(Data)
    /// Only TIFF: converted to PNG by `message`.
    case tiff(Data)
    /// Marked transient / auto-generated / concealed (nspasteboard.org): not sent.
    case skipped(String)

    /// Echo-guard hash (cheap; computed before any conversion).
    public var hash: UInt64? {
        switch self {
        case let .text(t): return ClipboardEchoGuard.hash(format: ClipboardData.formatText, Data(t.utf8))
        case let .png(d), let .tiff(d): return ClipboardEchoGuard.hash(format: ClipboardData.formatPNG, d)
        case .skipped: return nil
        }
    }

    public var needsConversion: Bool { if case .tiff = self { return true } else { return false } }

    /// Build the message to send. TIFF -> PNG conversion happens here (can take tens of ms for a
    /// large image: call it off the main thread when `needsConversion`). Never truncates.
    public func message(seq: UInt32, maxBytes: Int) -> Result<ClipboardData, ClipboardRefusal> {
        let limit = min(maxBytes, ClipboardData.maxBytes)
        switch self {
        case let .text(t):
            let n = t.utf8.count
            if n > limit { return .failure(.init("text too large (\(clipboardSize(n)) > \(clipboardSize(limit))), not sent")) }
            return .success(ClipboardData(seq: seq, text: t))
        case let .png(p):
            if p.count > limit { return .failure(.init("image too large (\(clipboardSize(p.count)) PNG > \(clipboardSize(limit))), not sent")) }
            return .success(ClipboardData(seq: seq, png: p))
        case let .tiff(t):
            guard let rep = NSBitmapImageRep(data: t), let p = rep.representation(using: .png, properties: [:]) else {
                return .failure(.init("could not convert TIFF image to PNG, not sent"))
            }
            if p.count > limit {
                return .failure(.init("image too large (\(rep.pixelsWide)x\(rep.pixelsHigh), \(clipboardSize(p.count)) PNG > \(clipboardSize(limit))), not sent"))
            }
            return .success(ClipboardData(seq: seq, png: p))
        case let .skipped(why):
            return .failure(.init(why))
        }
    }
}

/// Untrusted PNG validation, done before anything decodes the image (decompression bombs).
public enum ClipboardPNG {
    /// Largest image accepted from the peer: 64 Mpx (= 256 MB RGBA), same as the Windows viewer.
    public static let maxPixels = 64 << 20

    /// Width/height from the PNG signature + IHDR (which must be the first chunk). Nil if the data
    /// is not a well-formed PNG header.
    public static func dimensions(_ d: Data) -> (width: Int, height: Int)? {
        let b = [UInt8](d.prefix(33))
        let sig: [UInt8] = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]
        guard b.count == 33, Array(b[0..<8]) == sig else { return nil }
        let be = { (o: Int) -> Int in Int(b[o]) << 24 | Int(b[o + 1]) << 16 | Int(b[o + 2]) << 8 | Int(b[o + 3]) }
        guard be(8) == 13, b[12...15].elementsEqual("IHDR".utf8) else { return nil }
        return (be(16), be(20))
    }

    /// Nil if acceptable, else why not.
    public static func refusal(_ d: Data) -> String? {
        guard let (w, h) = dimensions(d) else { return "received image is not a PNG, ignored" }
        if w == 0 || h == 0 { return "received PNG has an empty size, ignored" }
        if w > maxPixels || h > maxPixels || w * h > maxPixels { return "received PNG is too large (\(w)x\(h) > \(maxPixels >> 20) Mpx), ignored" }
        return nil
    }
}

public enum ClipboardPasteboard {
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    /// Sender rules: skip transient/auto-generated, and concealed (passwords) unless
    /// `syncConcealed`; non-empty text wins; else PNG; else TIFF.
    public static func read(_ pb: NSPasteboard, syncConcealed: Bool = false) -> PasteboardContent? {
        let types = pb.types ?? []
        if types.contains(transientType) || types.contains(autoGeneratedType) {
            return .skipped("transient/auto-generated pasteboard content, not sent")
        }
        if !syncConcealed && types.contains(concealedType) {
            return .skipped("concealed pasteboard content (password manager), not sent — set host.json clipboard.syncConcealed to sync it")
        }
        if let s = pb.string(forType: .string), !s.isEmpty { return .text(ClipboardText.toWire(s)) }
        if let p = pb.data(forType: .png) { return .png(p) }
        if let t = pb.data(forType: .tiff) { return .tiff(t) }
        return nil
    }

    /// Validate a received clipboard and render TIFF for apps that only read TIFF (call off the
    /// main thread). An invalid PNG is dropped (the text, if any, is kept).
    public static func prepare(_ c: ClipboardData) -> Result<(ClipboardData, tiff: Data?), ClipboardRefusal> {
        if c.payloadBytes > ClipboardData.maxBytes {
            return .failure(.init("ignoring oversized clipboard (\(clipboardSize(c.payloadBytes)))"))
        }
        guard let png = c.png else {
            return c.text == nil ? .failure(.init("empty clipboard message ignored")) : .success((c, nil))
        }
        // Check signature + IHDR size before any decoder sees the bytes.
        if let why = ClipboardPNG.refusal(png) {
            guard let t = c.text else { return .failure(.init(why)) }
            return .success((ClipboardData(seq: c.seq, text: t), nil))
        }
        guard let rep = NSBitmapImageRep(data: png) else {
            guard let t = c.text else { return .failure(.init("received image is not a valid PNG, ignored")) }
            return .success((ClipboardData(seq: c.seq, text: t), nil))
        }
        return .success((c, rep.tiffRepresentation))
    }

    /// Replace the pasteboard's contents. Returns the changeCount after the write (the echo marker).
    @discardableResult
    public static func write(_ c: ClipboardData, tiff: Data?, to pb: NSPasteboard) -> Int {
        pb.clearContents()
        if let t = c.text { pb.setString(t, forType: .string) }
        if let png = c.png {
            pb.setData(png, forType: .png)
            if let tiff { pb.setData(tiff, forType: .tiff) }
        }
        return pb.changeCount
    }
}

/// "123 bytes" / "4.2 MiB".
public func clipboardSize(_ n: Int) -> String {
    n >= 1 << 20 ? String(format: "%.1f MiB", Double(n) / 1_048_576) : "\(n) bytes"
}

public extension ClipboardData {
    /// Log summary without the content itself (it may be a password).
    var summary: String {
        var parts: [String] = []
        if let t = text { parts.append("text \(clipboardSize(t.utf8.count))") }
        if let p = png { parts.append("png \(clipboardSize(p.count))") }
        return (parts.isEmpty ? "empty" : parts.joined(separator: " + ")) + " (seq \(seq))"
    }
}
